import AppKit
import CryptoKit

public enum ClipKind: String, Sendable {
    case text, richText, image, file, colour
    /// Read from a text copy's words, never stored (ClipboardCapture.kind(reading:)).
    case link, email

    /// The kind as the panel names it: Rich text in two words (card agent-bo-95422994).
    public var label: String { self == .richText ? "Rich text" : rawValue.capitalized }
}

/// One copy as Pilot keeps it: every representation worth pasting back, plus the plain text it is searched by.
public struct ClipItem: Equatable, Sendable {
    public var kind: ClipKind
    public var text: String
    /// One dictionary per pasteboard item (a copy of three files is three), pasteboard type → data,
    /// written back as-is with writeObjects when the copy is pasted.
    public var contents: [[String: Data]]
    public var sourceApp: String?

    /// A copy of plain text only, as split, merge, a format or an edit makes (card agent-bo-95422784).
    public static func plainText(_ text: String, sourceApp: String?) -> ClipItem {
        ClipItem(kind: .text, text: text, contents: [[NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]], sourceApp: sourceApp)
    }

    /// Same contents, same item: copying it again moves it to the top instead of adding a duplicate.
    public var contentHash: String {
        var hasher = SHA256()
        for (index, item) in contents.enumerated() {
            for (type, data) in item.sorted(by: { $0.key < $1.key }) {
                hasher.update(data: Data("\(index):\(type)".utf8))
                hasher.update(data: data)
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

/// Decides whether a copy is kept and reads it into a ClipItem (SPEC.md, the Clipboard history line).
public struct ClipboardCapture: Sendable {
    /// nspasteboard.org markers: a password manager's copy, a copy meant to vanish, a generated one.
    public static let skippedTypes: Set<NSPasteboard.PasteboardType> = [concealed, transient, .init("org.nspasteboard.AutoGeneratedType")]
    /// A password manager's copy.
    public static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// A copy meant to vanish; Pilot marks its own plain-text paste with it.
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// The representations kept for pasting back. TIFF only when there is no PNG: a screenshot's TIFF is
    /// uncompressed and tens of megabytes.
    static let keptTypes: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .fileURL, .png, .tiff, .color]

    public var ignoredApps = Set(ClipboardSettings.default.ignoredApps)
    /// Off: a copy that is only an image is not kept (Settings › Clipboard, Save images).
    public var saveImages = true
    /// The markers that make a copy one not to read; plain paste reads a transient copy too (card agent-bo-95423072).
    public var skipped = skippedTypes

    public init() {}

    public func capture(_ pasteboard: NSPasteboard, sourceApp: String?) -> ClipItem? {
        if let sourceApp, ignoredApps.contains(sourceApp) { return nil }
        // The pasteboard's own type list covers every item, including types an item only promises.
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: skipped) else { return nil }

        let contents: [[String: Data]] = (pasteboard.pasteboardItems ?? []).map { item in
            let present = Set(item.types)
            var kept: [String: Data] = [:]
            for type in Self.keptTypes where present.contains(type) && !(type == .tiff && present.contains(.png)) {
                kept[type.rawValue] = item.data(forType: type)
            }
            return kept
        }.filter { !$0.isEmpty }
        let string: (NSPasteboard.PasteboardType) -> [String] = { type in
            contents.compactMap { $0[type.rawValue].map { String(decoding: $0, as: UTF8.self) } }
        }
        let files = string(.fileURL).compactMap { URL(string: $0)?.path }
        let text = files.isEmpty ? string(.string).first ?? "" : files.joined(separator: "\n")

        let kind: ClipKind
        if !files.isEmpty {
            kind = .file
        } else if types.contains(.color) || Self.isColourLiteral(text) {
            kind = .colour
        } else if !text.isEmpty {
            kind = types.isDisjoint(with: [.rtf, .html]) ? .text : .richText
        } else if !types.isDisjoint(with: [.png, .tiff]), saveImages {
            kind = .image
        } else {
            return nil
        }
        return ClipItem(kind: kind, text: text, contents: contents, sourceApp: sourceApp)
    }

    /// A text copy is a link when it is one URL with a scheme and nothing else, an email when it is one address
    /// (card agent-bo-95422781). Read from the text each time the store lists it, so copies kept before then get
    /// them too; a text over 2 KB is neither, so a huge copy is never scanned.
    static func kind(reading stored: ClipKind, _ text: String) -> ClipKind {
        guard stored == .text || stored == .richText, text.utf8.count <= 2048 else { return stored }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if (try? link.wholeMatch(in: trimmed)) != nil { return .link }
        if (try? email.wholeMatch(in: trimmed)) != nil { return .email }
        return stored
    }
    // Made once: a literal in the function was built again for every row of every listing.
    nonisolated(unsafe) private static let link = /(?i)[a-z][a-z0-9+.\-]*:\/\/\S+/
    nonisolated(unsafe) private static let email = /[^\s@]+@[^\s@]+\.[^\s@]+/

    /// #rgb, #rrggbb, #rrggbbaa, rgb(…) or rgba(…), the whole copy and nothing else.
    static func isColourLiteral(_ text: String) -> Bool { colourValue(text) != nil }

    /// A colour literal's colour as 0xRRGGBB (alpha dropped), the one parser capture and the panel's swatch share; nil
    /// when the copy is not one.
    public static func colourValue(_ text: String) -> UInt32? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if let m = trimmed.wholeMatch(of: /(?i)#([0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})/) {
            let digits = String(m.1)
            let six = digits.count == 3 ? digits.map { "\($0)\($0)" }.joined() : String(digits.prefix(6))
            return UInt32(six, radix: 16)
        }
        guard let m = trimmed.wholeMatch(of: /(?i)rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(,\s*[\d.]+\s*)?\)/),
              let r = UInt32(m.1), let g = UInt32(m.2), let b = UInt32(m.3) else { return nil }
        return min(r, 255) << 16 | min(g, 255) << 8 | min(b, 255)
    }
}
